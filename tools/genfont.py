#!/usr/bin/env python3
"""Generate src/font.zig: an 8x16 ASCII bitmap font.

Rendered from a system monospace font with Pillow. The generated file is a
plain bitmap and is checked in so the kernel build has no font dependency.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CELL_W, CELL_H = 8, 16
FIRST, LAST = 32, 126
SIZE = 13
BASELINE = 12

FONT = "/usr/share/fonts/liberation/LiberationMono-Regular.ttf"


def render(font_path: str, size: int, baseline: int):
    font = ImageFont.truetype(font_path, size)
    glyphs = []
    for code in range(FIRST, LAST + 1):
        img = Image.new("L", (CELL_W, CELL_H), 0)
        draw = ImageDraw.Draw(img)
        ch = chr(code)
        draw.text((0, baseline), ch, font=font, fill=255, anchor="ls")
        rows = []
        for y in range(CELL_H):
            bits = 0
            for x in range(CELL_W):
                if img.getpixel((x, y)) >= 100:
                    bits |= 1 << (7 - x)
            rows.append(bits)
        glyphs.append(rows)
    return glyphs


def main() -> int:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("src/font.zig")
    glyphs = render(FONT, SIZE, BASELINE)
    lines = [
        "// Generated by tools/genfont.py from Liberation Mono (SIL OFL 1.1).",
        "// 8x16 bitmap, ASCII 32..126, one byte per scanline, MSB = leftmost pixel.",
        "",
        f"pub const width: usize = {CELL_W};",
        f"pub const height: usize = {CELL_H};",
        f"pub const first: u8 = {FIRST};",
        f"pub const last: u8 = {LAST};",
        "",
        "pub const glyphs = [last - first + 1][height]u8{",
    ]
    for code, rows in zip(range(FIRST, LAST + 1), glyphs):
        body = ", ".join(f"0x{b:02x}" for b in rows)
        lines.append(f"    .{{ {body} }}, // {code} {chr(code)!r}")
    lines.append("};")
    lines.append("")
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(glyphs)} glyphs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
